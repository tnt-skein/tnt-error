--- Крюки внутренней поломки: кому ещё сказать о происшествии.
---
--- О поломке каталог пишет в журнал сам (`Registry:internal`), и запись
--- эта одна. Но журнал — не единственный, кому нужно знать о поломке:
--- приёмнику происшествий, который группирует одинаковые поломки и
--- считает их повторы, нужно то же событие с тем же опознавателем —
--- по нему событие сходится с записью журнала и с ответом клиенту.
--- Второй опознаватель развёл бы их, поэтому о поломке сообщается там,
--- где номер выдан, а не выше по стеку, где его пришлось бы угадывать.
---
--- Кто слушает, каталог не знает: крюк приходит аргументом —
--- `errors.hook(имя, крюк)` ставит, заменяет или снимает его, — и
--- зависимости от слушателя у пакета нет.
---
---     errors.hook('app.alert', function(failure, cause)
---         -- failure — отказ с опознавателем и стеком, cause — причина как есть
---     end)
---
--- **Крюки общие на процесс, а не на каталог.** Каталоги заводятся и внутри
--- пакетов — у ядра приложения свой, у панели свой, — и до них
--- приложение не дотягивается; крюк, поставленный одному каталогу,
--- не услышал бы поломок в остальных.
---
--- **Крюк получает причину как есть.** В отказе причина лежит описанием —
--- строкой для журнала, с вырезанными тайнами. Слушателю со своим разбором
--- нужна она сама: цепочка ошибок box, отказ со стеком внутри. Тайны
--- в ней не вырезаны, и прятать их — дело слушателя.
---
--- **Крюк зовётся под `pcall`** и по порядку постановки. Поломку сообщают
--- на пути отказа, и бросок слушателя не вправе унести с собой отказ,
--- который уже собран и записан: о сорвавшемся крюке пишется `warn` с его
--- именем, а остальные крюки зовутся дальше. Уступать и ждать крюку
--- нельзя: поломку заводят и посреди транзакции.

local log = require('tnt.log').new('tnt.error')

local Module = {}

--- Уровень вины: строка того, кто позвал `hook`.
local CALLER = 2

--- Имена крюков в порядке постановки.
---@type string[]
local order = {}

--- Крюки по именам.
---@type table<string, fun(failure: TntError, cause: any)>
local hooks = {}

--- Место поставленного крюка в порядке постановки.
---@param name string
---@return integer|nil
local function position(name)
    for index, known in ipairs(order) do
        if known == name then
            return index
        end
    end
end

--- Ставит, заменяет или снимает крюк.
---
--- Замена оставляет крюк на прежнем месте: повторная постановка под тем
--- же именем безвредна — так слушателя ставят и при запуске, и при
--- перечитывании настроек. Снятый и поставленный снова встаёт последним.
---@param name string Имя крюка: по нему крюк снимают и о нём пишут в журнал
---@param hook (fun(failure: TntError, cause: any))|nil Крюк; `nil` снимает
function Module.set(name, hook)
    if type(name) ~= 'string' or name == '' then
        error(
            ('имя крюка — непустая строка, а не %s'):format(
                name == '' and 'пустая' or type(name)
            ),
            CALLER
        )
    end

    if hook ~= nil and type(hook) ~= 'function' then
        error(('крюк — функция, а не %s'):format(type(hook)), CALLER)
    end

    if hooks[name] == nil then
        -- Новый встаёт последним; снимать несуществующий нечего.
        if hook ~= nil then
            table.insert(order, name)
        end
    elseif hook == nil then
        table.remove(order, position(name) --[[@as integer]])
    end

    hooks[name] = hook
end

--- Имена крюков в порядке постановки.
---@return string[]
function Module.names()
    return table.copy(order)
end

--- Сообщает крюкам о поломке и отдаёт её же.
---
--- Отдаёт, чтобы каталог мог сообщить и вернуть отказ одним выражением:
--- сообщение — последнее, что делается с поломкой, когда она уже
--- записана и собрана.
---@param failure TntError Внутренняя поломка
---@param cause any Причина как есть
---@return TntError failure
function Module.fired(failure, cause)
    for _, name in ipairs(order) do
        local ok, err = pcall(hooks[name], failure, cause)

        if not ok then
            log.warn(('крюк внутренней поломки «%s» не отработал'):format(name), {
                incident = failure.incident,
                err = tostring(err),
            })
        end
    end

    return failure
end

return Module
