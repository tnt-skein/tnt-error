--- Что клиент готов принять: страницу или тело по договору отказа.
---
--- Один и тот же отказ уходит и браузеру, и сценарию, а нужно им разное:
--- сценарий разбирает поля, человек читает страницу. Кто именно
--- спрашивает, говорит сам запрос заголовком `Accept` (RFC 9110, §12.5.1),
--- и гадать по виду пути, по наличию куки или по способу не нужно.
---
--- Правило одно и оно строгое: страница уходит тому, кто попросил её
--- прямо — назвал `text/html` (или `application/xhtml+xml`) и назвал его
--- весомее, чем тело данных. Всё прочее получает прежний JSON. Отсюда
--- и обращение с видом «всё равно какой» (звёздочка дробь звёздочка):
--- так говорят `curl`, `fetch` без заголовка и всякий клиент, которому
--- и правда всё равно, — а тело отказа читает машина, и менять его
--- молча из-за этого нельзя.
---
--- Вес `q` разбирается, потому что без него браузер и сценарий
--- неразличимы: клиент API, готовый и на страницу, пишет
--- `application/json, text/html;q=0.1` — он назвал оба вида, и решает
--- именно вес.

local Module = {}

--- Заголовок, которым клиент называет желаемое.
---
--- Имена заголовков запроса приходят в нижнем регистре — это договор
--- границы HTTP (`TntRouterRequest`), и второго написания здесь не ищут.
Module.HEADER = 'accept'

--- Виды, которые значат «покажи страницу».
---
--- `application/xhtml+xml` рядом с `text/html` не для красоты: браузеры
--- называют его в том же перечне и с тем же весом, а клиент, назвавший
--- только его, просит ровно страницу.
local PAGE_TYPES = { ['text/html'] = true, ['application/xhtml+xml'] = true }

--- Виды, которые значат «отдай тело отказа».
---
--- Оба вида, которыми подписан ответ каталога: клиент, назвавший вид
--- нашего тела, получает тело, даже если рядом поминает страницу.
local DATA_TYPES = { ['application/json'] = true, ['application/problem+json'] = true }

--- Вес вида, который назвали без `q`: по RFC 9110 это единица.
local FULL = 1

--- Вес, с которым вид не называли вовсе.
local NONE = 0

--- Образец веса в параметрах записи: `;q=0.9`.
---
--- Вес начинается с цифры: `q=.5` и `q=-1` записью RFC не считаются,
--- и такая запись читается как «веса не назвали».
local WEIGHT = ';%s*q%s*=%s*([%d][%d%.]*)'

--- Запись перечня: имя вида и его параметры одной выборкой.
---
--- Имя — связка знаков без пробелов, запятых и точки с запятой: отступы
--- вокруг запятой RFC разрешает, а параметры идут после `;`. Параметры —
--- всё до следующей запятой, вместе с самой точкой с запятой.
local ENTRY = '([^,;%s]+)([^,]*)'

--- Вес одной записи перечня.
---
--- Негодный `q` — `q=абв`, `q=1.2.3` — считается за единицу, а не роняет
--- разбор: заголовок пишет клиент, и отказывать ему в ответе об отказе
--- было бы дурной шуткой. Вес больше единицы RFC не знает, и такая
--- запись читается как `q=1`, а не как «важнее всего на свете».
---@param params string Параметры записи: всё после имени вида
---@return number
local function quality(params)
    local said = params:match(WEIGHT)

    if said == nil then
        return FULL
    end

    local weight = tonumber(said)

    if weight == nil then
        return FULL
    end

    return math.min(weight, FULL)
end

--- Веса страницы и данных в перечне `Accept`.
---
--- Берётся наибольший вес из названных видов каждого рода: клиент вправе
--- назвать `text/html` дважды с разным весом, и решает больший.
---@param accept string
---@return number page Вес страницы
---@return number data Вес тела данных
local function weighed(accept)
    ---@type number, number
    local page, data = NONE, NONE

    -- Перечень приводится к нижнему регистру целиком: RFC не велит
    -- различать регистр ни у вида, ни у имени параметра, а значение
    -- веса — цифры, которым регистр безразличен.
    for kind, params in accept:lower():gmatch(ENTRY) do
        local weight = quality(params)

        if PAGE_TYPES[kind] then
            page = math.max(page, weight)
        elseif DATA_TYPES[kind] then
            data = math.max(data, weight)
        end
    end

    return page, data
end

--- Просит ли клиент страницу.
---
--- Запрос берётся целиком, а не заголовком: слой и обработчик отказов
--- получают его как есть, и разбирать его по дороге значило бы завести
--- второе место, где известен вид запроса. Запроса нет вовсе — страницы
--- нет: отказ, собранный без запроса, уходит телом по договору.
---@param request any Запрос по договору границы HTTP
---@return boolean
function Module.wants_page(request)
    if type(request) ~= 'table' or type(request.headers) ~= 'table' then
        return false
    end

    local accept = request.headers[Module.HEADER]

    if type(accept) ~= 'string' then
        return false
    end

    local page, data = weighed(accept)

    -- Равный вес отдаётся данным: клиент, назвавший оба вида одинаково,
    -- ничего о себе не сказал, а тело отказа — договор, и менять его
    -- при равенстве нельзя. Отдельной проверки на ноль не нужно: вес
    -- не бывает отрицательным, и «больше нуля» у страницы следует
    -- из того, что он больше веса данных.
    return page > data
end

return Module
