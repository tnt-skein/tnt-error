--- Отказ как значение: слой поверх слоя.
---
--- Отказ путешествует снизу вверх и по дороге обрастает смыслом. Внизу
--- «сервер молчит» — это правда, но человеку она ничего не говорит.
--- Выше «соединение не открылось», ещё выше «письмо не ушло». Каждый
--- слой знает ровно столько, сколько видно с его высоты, и выбрасывать
--- нижние нельзя: без них дежурный не поймёт, что чинить.
---
--- Поэтому отказ — не строка, а цепочка. Наружу уходит верхний слой,
--- в журнал — вся цепочка целиком.
---
--- Главное свойство, на котором держится весь пакет: поле `message`
--- у любого слоя безопасно показать человеку. Оно либо взято из каталога,
--- где его написал разработчик, либо написано разработчиком прямо
--- в обёртке. Текст, про который мы не знаем, кто его сочинил, — чужой
--- отказ, стек, ответ библиотеки, — живёт только в `cause`, и ответ,
--- собранный пакетом, его не показывает. Сериализатор этого не держит:
--- `__serialize` отдаёт `cause` журналу, а с ним и консоли, `net.box`,
--- `json` и `msgpack`. Прикладной код, который сам вернёт отказ по iproto
--- или положит его в тело ответа, отдаст причину наружу.
---
--- Рядом со своим отказом здесь живёт признание чужого. Соседние пакеты
--- отказывают на границе HTTP раньше, чем до дела дойдёт этот: роутер
--- отвечает 404 и 405 сам, до всякого обработчика. Такой отказ не наш —
--- метатаблицы на нём нет и быть не может, — но и внутренней поломкой
--- он не является: статус у него осмысленный, слово сказано, о записи
--- в журнале позаботился тот, кто отказал.
---
--- И признание брошенного под чужим перехватом: конвейер слоёв ловит
--- бросок обработчика раньше каталога и отдаёт отказ упавшего шага,
--- а брошенное кладёт в него полем `raised` как есть. Наш отказ или
--- чужой отказ границы HTTP, брошенный нарочно, узнаётся и там.

local Module = {}

---@class TntError
---@field code string Код отказа из каталога
---@field status integer Статус ответа HTTP
---@field title string Краткое имя рода отказа: не меняется от случая к случаю
---@field message string Строка для человека, уже с подстановками
---@field type string|nil URI рода отказа
---@field expected boolean Ожидаемый отказ или внутренняя поломка
---@field incident string|nil Опознаватель происшествия
---@field headers table<string, string>|nil Заголовки ответа, которых требует статус
---@field params table Подстановки, из которых уже вырезаны тайны
---@field explained boolean|nil Слово сказано `explain`: своё слово разработчика, по коду его не переводят
---@field cause TntError|string|nil Из-за чего случилось
---@field traceback string|nil Стек на месте поломки — только для журнала

--- Чужой отказ на границе HTTP: договор, общий с соседними пакетами.
---
--- Обязательно здесь одно — числовой `status`. Остальное необязательно:
--- кто отказал, тот и решает, есть ли ему что добавить.
---@class TntErrorRefusal
---@field status integer Статус ответа HTTP: 4xx или 5xx
---@field message string|nil Слово для человека; его написал разработчик
---@field code string|nil Код отказа, если он у отказавшего есть
---@field incident string|nil Опознаватель уже сделанной записи журнала
---@field headers table<string, string>|nil Заголовки, которых требует статус

--- Границы статуса, который считается отказом.
---
--- Только 4xx и 5xx: таблица с успешным статусом — это ответ, а не отказ,
--- и принимать её за отказ значило бы молча превращать промах вызывающего
--- в готовый ответ клиенту.
local MIN_STATUS = 400
local MAX_STATUS = 599

--- Общая метатаблица всех отказов. По ней отказ и узнаётся: поля можно
--- подделать все до одного, метатаблицу — нет, она закрыта в этом модуле.
local Failure = {}

--- Чем разделяются слои в цепочке.
local SEPARATOR = ': '

--- Слои цепочки сверху вниз, по строке на слой.
---@param err any
---@return string[]
function Module.chain(err)
    local said = {}
    local at = err

    while at ~= nil do
        if Module.is(at) then
            table.insert(said, at.message)
            at = at.cause
        else
            -- Причина не наша: чужой отказ, строка, объект box.error.
            -- Дальше цепочка не идёт — разбирать чужое устройство нечем.
            table.insert(said, tostring(at))
            at = nil
        end
    end

    return said
end

--- Вся цепочка одной строкой: «письмо не ушло: соединение не открылось:
--- сервер молчит». Годится для журнала, но не для ответа.
---@param self TntError
---@return string
function Failure.__tostring(self)
    return table.concat(Module.chain(self), SEPARATOR)
end

--- Отказ для записи журнала и для сериализаторов Tarantool: поля, а не строка.
---
--- Строкой цепочки отказ в журнале не найти ни по коду, ни по опознавателю
--- происшествия — только полнотекстовым поиском по слову, которое
--- к тому же меняется от случая к случаю. Поэтому наружу идут поля,
--- по которым отказ ищут: код, статус, слово, опознаватель и причина.
---
--- Причина отдаётся как есть: наш отказ в ней сериализуется этим же видом,
--- чужая строка или `box.error` — своим. Стек не отдаётся: он нужен
--- записи о самом происшествии, где его пишут отдельным полем, а в каждой
--- записи, куда отказ попал попутно, он растягивал бы строку на экран.
--- Подстановки, заголовки и род тоже остаются дома: всё нужное из них
--- уже вошло в слово.
---@param self TntError
---@return table
function Failure.__serialize(self)
    return {
        code = self.code,
        status = self.status,
        message = self.message,
        incident = self.incident,
        cause = self.cause,
    }
end

--- Заводит отказ.
---@param fields table
---@return TntError
function Module.new(fields)
    return setmetatable(fields, Failure)
end

--- Наш ли это отказ.
---@param value any
---@return boolean
function Module.is(value)
    return getmetatable(value) == Failure
end

--- Чужой ли это отказ на границе HTTP.
---
--- Признак один и он явный — число в `status`. По виду прочих полей
--- пакет ничего не решает: догадку «код это или слово для человека»
--- отсюда убрали, и заводить её заново под другим именем нельзя. Чужое
--- `{ status = 'ok' }` или запись работы `{ status = 1 }` отказом
--- не считаются: за отказ принимается только осмысленный статус ответа.
---
--- Свой отказ здесь не разбирается: о нём спрашивают раньше и другим
--- вызовом.
---@param value any
---@return boolean
function Module.refuses(value)
    if type(value) ~= 'table' then
        return false
    end

    local status = value.status

    if type(status) ~= 'number' or status % 1 ~= 0 then
        return false
    end

    return status >= MIN_STATUS and status <= MAX_STATUS
end

--- Отказ, брошенный под чужим перехватом, либо nil.
---
--- Бросок ловит и тот, кто стоит ниже каталога: конвейер слоёв зовёт
--- каждый шаг под своим `xpcall` и отдаёт наверх отказ упавшего шага,
--- а брошенное кладёт в него полем `raised`. Бросают и нарочно:
--- обработчик вправе отказать броском — «нет такого клиента», — и по слову
--- упавшего шага такой отказ уже не узнать, статус и код остались
--- в брошенном.
---
--- Признаки те же, по которым `guard` судит пойманное им самим: в поле
--- лежит наш отказ — по метатаблице — либо чужой отказ границы HTTP —
--- по числу в `status`. Всё прочее брошенное — строка, объект ошибки,
--- таблица без признаков — отказом не считается: это поломка, и в записи
--- о ней причиной идёт отказ упавшего шага целиком — его слово называет
--- шаг, а стек лежит рядом. Поле читается мимо метатаблицы: о причине
--- пишут там, где поломка уже случилась, и чужой `__index`, бросив, унёс
--- бы с собой запись о первой.
---@param value any
---@return TntError|TntErrorRefusal|nil
function Module.thrown(value)
    if type(value) ~= 'table' then
        return nil
    end

    local raised = rawget(value, 'raised')

    if Module.is(raised) or Module.refuses(raised) then
        return raised
    end

    return nil
end

return Module
