--- Готовый слой для `tnt.middleware` и обработчик для `tnt.router`.
---
--- Здесь ровно две функции: одна зовёт следующего под перехватом, вторая
--- превращает отказ в ответ. Обе умышленно не разбирают запрос: договор
--- слоя `(запрос, следующий)` и договор обработчика отказов
--- `(отказ, запрос)` объявлены в соседних пакетах, и повторять их здесь
--- значило бы завести второе место, где они живут.
---
--- Запрос обе передают каталогу как есть, и нужен он одному — выбору
--- вида ответа: браузеру, попросившему `text/html`, уходит страница,
--- остальным прежнее тело (`tnt.error.accept`). Отказ роутера — 404, 405
--- с заголовком `Allow`, 400 — доходит сюда обычной таблицей со статусом;
--- узнаёт её `Registry:of` по договору границы HTTP и сохраняет и статус,
--- и заголовки, и опознаватель уже сделанной роутером записи.
---
--- Слой ставится самым верхним. Ниже него любой отказ уже поймали
--- и превратили в ответ, а выше — некому: паника, дошедшая до сервера,
--- превращается в пустой ответ 500 без опознавателя, и найти её в журнале
--- будет нечем.

local Module = {}

--- Слой: зовёт следующий обработчик под перехватом.
---
--- Перехватывается и паника, и пара `nil, err` — второе не менее важно.
--- Отказ, вернувшийся парой, обычно доходит до сервера строкой, и наружу
--- уезжает текст, который писали для дежурного, а не для клиента.
---@param registry TntErrorRegistry
---@return fun(request: any, nxt: fun(request: any): any): any
function Module.middleware(registry)
    return function(request, nxt)
        local response, err = registry:guard(nxt, request)

        if err ~= nil then
            return registry:response(err, request)
        end

        return response
    end
end

--- Обработчик отказа для маршрутизатора.
---
--- Берёт что угодно — свой отказ, чужой отказ границы HTTP, чужую строку,
--- объект `box.error` — и отдаёт готовый ответ.
---@param registry TntErrorRegistry
---@return fun(err: any, request: any): table
function Module.handler(registry)
    return function(err, request)
        return registry:response(err, request)
    end
end

return Module
