--- Опознаватель происшествия: то единственное, что связывает ответ
--- человеку с записью в журнале.
---
--- Человек звонит и говорит: «у меня написано 4KJ7-QW9M». Дежурный ищет
--- это в журнале и видит всё: стек, чужой отказ, адрес, по которому
--- не достучались. Поэтому опознаватель обязан произноситься вслух —
--- и отсюда все решения ниже.
---
--- Азбука Крокфорда: тридцать две буквы и цифры без `I`, `L`, `O` и `U`.
--- Первые три неотличимы от единицы и нуля в трубке и на бумаге, `U`
--- выброшена, чтобы из случайных букв не сложилось бранное слово. Только
--- заглавные: «эс маленькая или большая» — лишний вопрос. Азбука живёт
--- в `tnt-id`, рядом с ULID, который пишется ею же: два списка одних
--- и тех же знаков однажды разошлись бы.
---
--- Восемь знаков двумя группами по четыре: `4KJ7-QW9M`. Это триллион
--- сочетаний — с запасом на все происшествия за всё время, пока живёт
--- запись журнала, и вчетверо короче UUID, который вслух не читается
--- вовсе.
---
--- Опознаватель ничего не значит: по нему нельзя узнать ни время, ни узел,
--- ни род поломки. Это нарочно — иначе он стал бы способом узнать
--- о внутренностях узла, ничего в него не посылая. **Поэтому из `tnt-id`
--- взята только азбука, а не способ порождения.** ULID и UUIDv7 несут
--- время в старших знаках: по опознавателю происшествия человек снаружи
--- узнал бы, когда именно узел сломался, а по двум соседним — сколько
--- поломок было между ними. Здесь каждый знак случаен.

local external = require('tnt.external')
local digest = require('digest')

local crockford = require('tnt.id.crockford')

local Module = {}

--- Азбука без похожих друг на друга знаков.
Module.ALPHABET = crockford.ALPHABET

--- Сколько знаков в опознавателе.
Module.LENGTH = 8

--- После скольких знаков ставится дефис.
Module.GROUP = 4

--- Чем разделяются группы.
Module.SEPARATOR = '-'

--- Настоящие средства.
local defaults = {
    -- Случайность берётся у ядра, а не у `math.random`: тот на всех
    -- файберах один и после `math.randomseed` от одинакового времени
    -- выдаёт на двух узлах одни и те же опознаватели.
    random = function(count)
        return digest.urandom(count)
    end,
}

local source = external.install(Module, defaults)

--- Новый опознаватель происшествия.
---
--- Каждый случайный байт становится знаком по своим пяти младшим битам:
--- байтов 256, знаков 32, и на каждый знак приходится ровно восемь
--- значений байта — перекоса нет.
---@return string
function Module.next()
    local letters = crockford.spell(source().random(Module.LENGTH))

    return crockford.group(letters, Module.GROUP, Module.SEPARATOR)
end

return Module
